/**
 * Renders one icon as an inline SVG. Its color comes from the text color of the parent, for example text-primary.
 *
 * @param {object} props The component props.
 * @param {string} props.name Which icon to draw, for example "calendar", "map-pin", "arrow-left", or a category icon like "code".
 * @param {number} [props.size] The width and height in pixels.
 * @param {number} [props.strokeWidth] The line thickness in the icon's 24-unit grid. Big icons pass a smaller number to stay thin.
 * @param {string} [props.className] Extra Tailwind classes.
 * @returns {JSX.Element} The icon.
 */
export default function Icon({ name, size = 16, strokeWidth = 2, className = '' }) {
  // aria-hidden hides the icon from screen readers, because the text or label next to it already says the same thing.
  return (
    <svg
      className={'shrink-0 ' + className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {iconShapes[name]}
    </svg>
  );
}
